#!/usr/bin/env python3
"""Validate an audit JSON against the schema, the codebook, and its frozen bundle.

    python scripts/validate_audit.py AUDIT.json --bundle BUNDLE_DIR [--json]

Exit 0 = valid, 1 = invalid, 2 = unusable input. These are deterministic
structural and referential checks: they catch invented ids, quotes,
selectors, source lines, untested behavior claims, and impossible boxes.
They cannot judge whether an interpretation is right; that needs human review.
"""

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _lib  # noqa: E402

EVIDENCE_COLLECTIONS = {
    "screenshot": ("assets", "missing_asset_ref", "screenshot"),
    "text": ("spans", "missing_span_ref", "text"),
    "interaction": ("events", "missing_event_ref", "interaction"),
    "dom": ("elements", "missing_element_ref", "dom"),
    "source": ("excerpts", "missing_excerpt_ref", "source"),
}
CONTEXT_FIELDS = {"purpose", "genre", "audience", "constraints"}
BEHAVIOR_FEATURES = {"INT-01", "INT-02", "DAT-02"}
# Phrases that suggest an authorship verdict or a probability score. Warnings only:
# whether a sentence makes such a claim is ultimately a human judgment.
VERDICT_PATTERNS = re.compile(
    r"(\b\d{1,3}\s?%\s*(ai|likely|probab|chance)|\bprobability (that|of)\b.*\b(ai|generated)|"
    r"\b(likely|probably|clearly|definitely) (ai[- ]generated|generated by|written by ai|made by ai)|"
    r"\bai detected\b|\bwas (ai[- ])?generated by\b|\bthis site is ai\b)",
    re.IGNORECASE,
)


class AuditCheck:
    def __init__(self, audit, bundle, report):
        self.a = audit
        self.b = bundle
        self.r = report
        self.codebook = _lib.load_codebook()
        self.features = _lib.features_by_id(self.codebook)

    # --- locations and evidence -------------------------------------------

    def location(self, loc, where):
        b, r = self.b, self.r
        if loc["region_id"] not in b.regions:
            r.error("unknown_region", f"{where}: region {loc['region_id']!r} is not in the bundle")
        if loc["state_id"] not in b.states:
            r.error("unknown_state", f"{where}: state {loc['state_id']!r} is not in the bundle")
        asset_id = loc["asset_id"]
        if asset_id is not None:
            if "screenshot" not in self.modalities:
                r.error("modality_unavailable", f"{where}: cites screenshot {asset_id!r} but screenshots are not available to this profile")
            elif asset_id not in b.assets:
                r.error("missing_asset_ref", f"{where}: asset {asset_id!r} is not in the bundle")
            elif b.assets[asset_id]["state_id"] != loc["state_id"]:
                r.error("asset_state_mismatch", f"{where}: asset {asset_id} shows state {b.assets[asset_id]['state_id']}, not {loc['state_id']}")
        box = loc["box"]
        if box is not None:
            if asset_id is None:
                r.error("box_without_asset", f"{where}: a box needs the asset_id it is normalized to")
            if box["x"] + box["width"] > 1 + 1e-9 or box["y"] + box["height"] > 1 + 1e-9:
                r.error("box_out_of_bounds", f"{where}: box {box} extends past the image (x + width and y + height must be <= 1)")
        if loc["selector"] is not None:
            if "dom" not in self.modalities:
                r.error("fabricated_selector", f"{where}: selector given but the bundle has no captured DOM")
            elif loc["selector"] not in b.selectors():
                r.error("fabricated_selector", f"{where}: selector {loc['selector']!r} does not appear in captured dom_elements")
        sref = loc["source_ref"]
        if sref is not None:
            self.source_lines(sref["excerpt_id"], sref["line_start"], sref["line_end"], where)

    def source_lines(self, excerpt_id, start, end, where):
        if "source" not in self.modalities:
            self.r.error("modality_unavailable", f"{where}: cites source but no source excerpts were supplied")
            return
        ex = self.b.excerpts.get(excerpt_id)
        if ex is None:
            self.r.error("missing_excerpt_ref", f"{where}: source excerpt {excerpt_id!r} is not in the bundle")
        elif not (ex["line_start"] <= start <= end <= ex["line_end"]):
            self.r.error("invalid_source_lines", f"{where}: lines {start}-{end} fall outside excerpt {excerpt_id} ({ex['line_start']}-{ex['line_end']})")

    def evidence(self, ev, where):
        """Check one evidence item; return the referenced interaction record, if any."""
        kind, ref = ev["kind"], ev["ref_id"]
        if kind == "context":
            if ref not in CONTEXT_FIELDS:
                self.r.error("missing_context_ref", f"{where}: context evidence must name one of {sorted(CONTEXT_FIELDS)}")
            if ev["quote"] is not None:
                self.r.error("quote_mismatch", f"{where}: context evidence cannot carry a quote")
            return None
        attr, missing_code, modality = EVIDENCE_COLLECTIONS[kind]
        if modality not in self.modalities:
            self.r.error("modality_unavailable", f"{where}: cites {kind} evidence {ref!r} but that modality is unavailable to this profile")
            return None
        record = getattr(self.b, attr).get(ref)
        if record is None:
            self.r.error(missing_code, f"{where}: {kind} reference {ref!r} is not in the bundle")
            return None
        if ev["quote"] is not None:
            if kind == "text":
                haystack = record["text"]
            elif kind == "source":
                haystack = record["text"]
            else:
                self.r.error("quote_mismatch", f"{where}: quotes are only allowed for text or source evidence")
                return None
            if _lib.normalize_space(ev["quote"]) not in _lib.normalize_space(haystack):
                self.r.error("quote_mismatch", f"{where}: quote {ev['quote']!r} is not in {kind} {ref}")
        return record if kind == "interaction" else None

    def common(self, item, where):
        for i, loc in enumerate(item["locations"]):
            self.location(loc, f"{where}.locations[{i}]")
        events = []
        for i, ev in enumerate(item["evidence"]):
            rec = self.evidence(ev, f"{where}.evidence[{i}]")
            if rec is not None:
                events.append(rec)
        return events

    # --- whole audit ---------------------------------------------------------

    def run(self):
        a, b, r = self.a, self.b, self.r
        if a["rubric_version"] != self.codebook["rubric_version"]:
            r.error("rubric_mismatch", f"rubric_version {a['rubric_version']} does not match codebook {self.codebook['rubric_version']}")
        if a["bundle_id"] != b.bundle_id:
            r.error("bundle_mismatch", f"audit is for bundle {a['bundle_id']!r}, not {b.bundle_id!r}")
        if a["bundle_hash"] != b.hash:
            r.error("bundle_mismatch", "bundle_hash does not match the bundle: wrong bundle, or the evidence changed after judging")
        try:
            prof = _lib.profile(a["analysis_profile"])
        except _lib.UsageError as err:
            r.error("unknown_profile", str(err))
            return
        self.modalities = _lib.available_modalities(b.manifest, a["analysis_profile"])
        profile_ids = [f["id"] for f in _lib.profile_features(a["analysis_profile"], self.codebook)]

        self.coverage(profile_ids, prof)
        for s in a["inventory"]["structure"]:
            if s["region_id"] not in b.regions:
                r.error("unknown_region", f"inventory.structure: region {s['region_id']!r} is not in the bundle")

        for key, id_field in [("findings", "finding_id"), ("contextual_exceptions", "exception_id"),
                              ("quality_observations", "observation_id"), ("exploratory_candidates", "candidate_id")]:
            ids = [x[id_field] for x in a[key]]
            dupes = sorted({i for i in ids if ids.count(i) > 1})
            if dupes:
                r.error("duplicate_id", f"{key}: duplicate ids {dupes}")

        for f in a["findings"]:
            self.finding(f, profile_ids)
        for x in a["contextual_exceptions"]:
            where = f"contextual_exceptions[{x['exception_id']}]"
            if x["feature_id"] not in self.features:
                r.error("unknown_feature", f"{where}: {x['feature_id']} is not in the codebook")
            self.common(x, where)
        for q in a["quality_observations"]:
            where = f"quality_observations[{q['observation_id']}]"
            if q["related_feature_id"] is not None and q["related_feature_id"] not in self.features:
                r.error("unknown_feature", f"{where}: related_feature_id {q['related_feature_id']} is not in the codebook")
            self.common(q, where)
        for c in a["exploratory_candidates"]:
            self.common(c, f"exploratory_candidates[{c['candidate_id']}]")
        for i, u in enumerate(a["untrusted_instructions_observed"]):
            kind = {"text": "text", "screenshot": "screenshot", "source": "source", "dom": "dom"}[u["ref_kind"]]
            self.evidence({"kind": kind, "ref_id": u["ref_id"], "quote": None, "description": u["description"]},
                          f"untrusted_instructions_observed[{i}]")

        self.duplicates_and_contradictions()
        self.status()
        texts = [a["summary"]["text"]] + [f["slop_association"]["reason"] for f in a["findings"]]
        for t in texts:
            if VERDICT_PATTERNS.search(t):
                r.warn("possible_authorship_claim", f"text may state an authorship verdict or probability: {t[:120]!r}")

    def coverage(self, profile_ids, prof):
        a, r = self.a, self.r
        cov = a["coverage"]
        for m in cov["assessed_modalities"]:
            if m not in self.modalities:
                r.error("modality_unavailable", f"coverage claims modality {m!r} was assessed, but it is not available to this profile and bundle")
        seen = {}
        for c in cov["features"]:
            fid = c["feature_id"]
            if fid in seen:
                r.error("duplicate_id", f"coverage.features lists {fid} twice")
            seen[fid] = c
            if fid not in self.features:
                r.error("unknown_feature", f"coverage.features: {fid} is not in the codebook")
            elif fid not in profile_ids:
                r.error("feature_not_in_profile", f"coverage.features: {fid} is not in profile {a['analysis_profile']}")
            elif c["status"] == "assessed" and not _lib.feature_assessable(self.features[fid], self.modalities):
                r.error("modality_unavailable", f"coverage marks {fid} assessed, but none of its required modality sets is available")
        for fid in profile_ids:
            if fid not in seen:
                r.warn("coverage_missing_feature", f"coverage.features has no entry for {fid}")
        self.feature_coverage = seen
        for c in cov["regions"]:
            if c["region_id"] not in self.b.regions:
                r.error("unknown_region", f"coverage.regions: region {c['region_id']!r} is not in the bundle")
            for sid in c["state_ids"]:
                if sid not in self.b.states:
                    r.error("unknown_state", f"coverage.regions: state {sid!r} is not in the bundle")

    def finding(self, f, profile_ids):
        r = self.r
        where = f"findings[{f['finding_id']}]"
        fid = f["feature_id"]
        feat = self.features.get(fid)
        events = self.common(f, where)
        if feat is None:
            r.error("unknown_feature", f"{where}: {fid} is not in the codebook")
            return
        if fid not in profile_ids:
            r.error("feature_not_in_profile", f"{where}: {fid} belongs to module {feat['module']!r}, not in profile {self.a['analysis_profile']}")
        if not _lib.feature_assessable(feat, self.modalities):
            r.error("modality_unavailable", f"{where}: {fid} needs one of {feat['modality_sets']}; available: {sorted(self.modalities)}")
        cov = self.feature_coverage.get(fid)
        if cov is not None and cov["status"] != "assessed":
            r.error("contradictory_status", f"{where}: coverage marks {fid} {cov['status']} but a finding uses it")
        if f["codebook_evidence_status"] != feat["evidence_status"]:
            r.error("status_upgrade", f"{where}: codebook_evidence_status must be {feat['evidence_status']!r} (from the codebook), got {f['codebook_evidence_status']!r}")
        if fid == "QLT-01" and not f["quality_to_slop_rationale"]:
            r.error("quality_without_rationale", f"{where}: QLT-01 belongs in quality_observations unless quality_to_slop_rationale explains the slop connection")
        if fid != "QLT-01" and f["quality_to_slop_rationale"]:
            r.warn("unused_field", f"{where}: quality_to_slop_rationale is only meaningful for QLT-01")
        for tag in f["secondary_tags"]:
            if tag not in self.features:
                r.error("unknown_feature", f"{where}: secondary tag {tag} is not in the codebook")
            elif tag == fid:
                r.error("duplicate_finding", f"{where}: secondary tag repeats the primary code")
        regions = {loc["region_id"] for loc in f["locations"]}
        if len(regions) < feat.get("min_regions", 1):
            r.error("insufficient_regions", f"{where}: {fid} needs evidence from at least {feat['min_regions']} regions, got {len(regions)}")
        if f["scope"] in ("page-pattern", "cross-region") and len(regions) < 2:
            r.error("insufficient_regions", f"{where}: a {f['scope']} finding must cite at least two recorded regions")
        not_completed = [e for e in events if e["execution_status"] != "completed"]
        completed = [e for e in events if e["execution_status"] == "completed"]
        if fid in BEHAVIOR_FEATURES or feat.get("requires_completed_interaction"):
            if not_completed:
                r.error("unobserved_action", f"{where}: cites interaction(s) {[e['event_id'] for e in not_completed]} that did not complete; untested behavior is unassessed, not broken")
            if not completed:
                r.error("unobserved_action", f"{where}: {fid} requires a completed recorded interaction")
            else:
                states = {loc["state_id"] for loc in f["locations"]}
                linked = {e["before_state_id"] for e in completed} | {e["after_state_id"] for e in completed}
                if not states & linked:
                    r.warn("state_not_linked", f"{where}: no location uses the before or after state of the cited interaction")
        elif not_completed:
            r.warn("unobserved_action", f"{where}: cites an interaction that did not complete")
        consequence = f["communication_or_interaction_consequence"]["level"]
        if consequence == "major" and not completed:
            r.error("consequence_without_evidence", f"{where}: a major consequence means a tested failure; cite the completed interaction")

    def duplicates_and_contradictions(self):
        a, r = self.a, self.r
        keys, phenomena = {}, {}
        for f in a["findings"]:
            key = (f["feature_id"], frozenset((l["region_id"], l["state_id"]) for l in f["locations"]))
            if key in keys:
                r.error("duplicate_finding", f"findings {keys[key]} and {f['finding_id']} describe the same feature at the same locations; merge them")
            keys[key] = f["finding_id"]
            pid = f["phenomenon_id"]
            if pid is not None:
                if pid in phenomena:
                    other = phenomena[pid]
                    if other["feature_id"] != f["feature_id"]:
                        r.error("phenomenon_multiple_codes", f"phenomenon {pid} has two primary codes ({other['feature_id']}, {f['feature_id']}); use one primary code and secondary_tags")
                    else:
                        r.error("duplicate_finding", f"findings {other['finding_id']} and {f['finding_id']} share phenomenon {pid}; record repeated occurrences as locations of one finding")
                else:
                    phenomena[pid] = f
        finding_spots = {(f["feature_id"], l["region_id"]) for f in a["findings"] for l in f["locations"]}
        for x in a["contextual_exceptions"]:
            for l in x["locations"]:
                if (x["feature_id"], l["region_id"]) in finding_spots:
                    r.error("contradictory_status", f"{x['feature_id']} at region {l['region_id']} is both a finding and contextual exception {x['exception_id']}")

    def status(self):
        a, r = self.a, self.r
        if a["status"] == "insufficient_evidence" and (a["findings"] or a["contextual_exceptions"]):
            r.error("contradictory_status", "status insufficient_evidence cannot carry findings or contextual exceptions")
        if a["status"] == "completed":
            partial_states = [s["state_id"] for s in self.b.manifest["states"] if s["load_status"] in ("partial", "failed")]
            if partial_states:
                r.warn("status_overclaims", f"status completed although states {partial_states} loaded partially or failed")
            abstained = [fid for fid, c in self.feature_coverage.items()
                         if c["status"] == "unassessed" and fid in self.features
                         and _lib.feature_assessable(self.features[fid], self.modalities)]
            if abstained:
                r.warn("status_overclaims", f"status completed although assessable features were left unassessed: {abstained}")


def validate(audit_or_path, bundle_dir):
    """Return a Report. Accepts a parsed audit dict or a path."""
    label = str(audit_or_path) if not isinstance(audit_or_path, dict) else audit_or_path.get("audit_id", "audit")
    report = _lib.Report(label)
    try:
        audit = audit_or_path if isinstance(audit_or_path, dict) else _lib.load_json(audit_or_path)
    except _lib.UsageError as err:
        report.error("invalid_json", str(err))
        return report
    for msg in _lib.schema_errors(audit, _lib.load_schema("audit.schema.json")):
        report.error("schema", msg)
    if report.errors:
        return report
    try:
        bundle = _lib.Bundle(bundle_dir)
    except _lib.UsageError as err:
        report.error("bundle_unreadable", str(err))
        return report
    AuditCheck(audit, bundle, report).run()
    return report


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("audit", help="audit JSON file")
    parser.add_argument("--bundle", required=True, help="the frozen bundle the audit was made from")
    parser.add_argument("--json", action="store_true", help="print a JSON report")
    args = parser.parse_args(argv)
    report = validate(args.audit, args.bundle)
    if args.json:
        print(json.dumps(report.as_dict(), indent=2))
    else:
        report.print()
    return 0 if report.ok else 1


if __name__ == "__main__":
    _lib.run_main(main)
